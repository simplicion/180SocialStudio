/**
 * Generates apps/social-studio-mobile/lib/features/studio/caption_languages_data.dart from CAPTION_LANGUAGES
 * (src/caption-languages.ts). Run: npx tsx packages/video-contracts/scripts/gen-caption-languages-dart.ts
 * tests/caption-languages.test.ts fails when the Dart file is not what this script would write.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { CAPTION_LANGUAGES } from "../src/caption-languages";

export const DART_LANGUAGES_PATH = join(__dirname, "../../../apps/social-studio-mobile/lib/features/studio/caption_languages_data.dart");

const str = (v: string | null): string => (v === null ? "null" : `'${v.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\$/g, "\\$")}'`);
const list = (v: string[]): string => `[${v.map(str).join(", ")}]`;

export function renderCaptionLanguagesDart(): string {
  const rows = CAPTION_LANGUAGES.map(
    (l) =>
      `  CaptionLanguage(\n` +
      `    code: ${str(l.code)},\n` +
      `    name: ${str(l.name)},\n` +
      `    nativeName: ${str(l.nativeName)},\n` +
      `    transcriptionCode: ${str(l.transcriptionCode)},\n` +
      `    script: ${str(l.script)},\n` +
      `    fontStack: ${list(l.fontStack)},\n` +
      `    maxCharsPerLine: ${l.maxCharsPerLine},\n` +
      `    maxCharsPerSecond: ${l.maxCharsPerSecond},\n` +
      `    rtl: ${l.rtl},\n` +
      `    noSpaces: ${l.noSpaces},\n` +
      `    hasCase: ${l.hasCase},\n` +
      `    casingLocale: ${str(l.casingLocale)},\n` +
      `    translateLanguage: ${str(l.translateAs.language)},\n` +
      `    translateRoman: ${l.translateAs.script === "roman"},\n` +
      `    aliases: ${list(l.aliases)},\n` +
      `  ),\n`
  );
  return (
    `// GENERATED by packages/video-contracts/scripts/gen-caption-languages-dart.ts from\n` +
    `// packages/video-contracts/src/caption-languages.ts. Do not edit by hand: edit the source and run\n` +
    `// \`npx tsx packages/video-contracts/scripts/gen-caption-languages-dart.ts\` (a test checks they match).\n\n` +
    `/// One caption language (see caption-languages.ts for the meaning of each field).\n` +
    `class CaptionLanguage {\n` +
    `  const CaptionLanguage({\n` +
    `    required this.code,\n    required this.name,\n    required this.nativeName,\n    required this.transcriptionCode,\n` +
    `    required this.script,\n    required this.fontStack,\n    required this.maxCharsPerLine,\n    required this.maxCharsPerSecond,\n` +
    `    required this.rtl,\n    required this.noSpaces,\n    required this.hasCase,\n    required this.casingLocale,\n` +
    `    required this.translateLanguage,\n    required this.translateRoman,\n    required this.aliases,\n  });\n\n` +
    `  final String code;\n  final String name;\n  final String nativeName;\n  final String? transcriptionCode;\n` +
    `  final String script;\n  final List<String> fontStack;\n  final int maxCharsPerLine;\n  final int maxCharsPerSecond;\n` +
    `  final bool rtl;\n  final bool noSpaces;\n  final bool hasCase;\n  final String? casingLocale;\n` +
    `  final String translateLanguage;\n  final bool translateRoman;\n  final List<String> aliases;\n}\n\n` +
    `const captionLanguageList = <CaptionLanguage>[\n${rows.join("")}];\n`
  );
}

if (require.main === module) {
  writeFileSync(DART_LANGUAGES_PATH, renderCaptionLanguagesDart(), "utf8");
  console.log(`wrote ${DART_LANGUAGES_PATH} (${CAPTION_LANGUAGES.length} languages)`);
}
